import assert from 'node:assert/strict';
import {tailoredInitial,validateProject,calculate} from './dist/model.mjs';
import {ensureScene} from './dist/layout-model.mjs';
import {defaultLibrary,ensureInstallation,makeBox,makeInstance,saveBoxTemplate,addBoxFromTemplate,routeSpecs,routeRecord,routeGeometry,routeAnchor,perimeterAnchor,assignCable,connectionWarnings,boxCapacity,projectCapacity,billOfMaterials,routeIssues,deleteRoute} from './dist/installation-model.mjs';
import {createDemoProject} from './dist/demo-project.mjs';

const p=tailoredInitial(),lib=defaultLibrary();ensureInstallation(p);ensureScene(p);
const bank=routeSpecs(p).find(s=>s.id.startsWith('bank:')),r=routeRecord(p,bank.id),g=routeGeometry(p,bank);
assert.ok(g.routeM>0);assert.equal(g.requiredM,g.routeM);assert.equal(g.allowanceM,0);
r.points.push({x:4,y:5});const bent=routeGeometry(p,bank);assert.ok(bent.routeM>g.routeM);
p.installation.slack={mode:'percent',value:10};assert.ok(Math.abs(routeGeometry(p,bank).requiredM-bent.routeM*1.1)<1e-8);
p.installation.slack={mode:'fixed',value:1};assert.ok(Math.abs(routeGeometry(p,bank).requiredM-bent.routeM-1)<1e-8);
assignCable(p,bank.id,lib.cables.find(c=>c.lengthM===1));assert.ok(routeGeometry(p,bank).shortByM>0);
assert.ok(calculate(p).warnings.some(w=>w.title==='Cable too short'));
const box=makeBox('Control rack'),ctrl=makeInstance(lib.components.find(c=>c.name==='Baldrick8'),'controller:c1'),button=makeInstance(lib.components.find(c=>c.name==='Push button'));box.components.push(ctrl,button);p.installation.boxes.push(box);ensureScene(p);
assert.equal(boxCapacity(p,box).used.pixelOutputs,4);assert.equal(projectCapacity(p).used.pixelOutputs,4);
const link={id:'link-test',boxId:box.id,fromComponent:ctrl.id,fromPort:'p1',toComponent:button.id,toPort:'signal1',acknowledged:false};p.installation.connections.push(link);assert.ok(connectionWarnings(p,link).length>0);
const input=makeInstance(lib.components.find(c=>c.name==='BaldrickInput'));box.components.push(input);
const signal={id:'link-input',boxId:box.id,fromComponent:button.id,fromPort:'signal1',toComponent:input.id,toPort:'in1',acknowledged:false};p.installation.connections.push(signal);
assert.equal(boxCapacity(p,box).used.digitalInputs,1);
const external={id:'link-external',boxId:box.id,fromComponent:ctrl.id,fromPort:'p1',fromKey:'box:'+box.id,toKey:'segment:'+p.chains[0].segments[0].id,kind:'data',name:'Box pixel output'};p.installation.connections.push(external);
const spec=routeSpecs(p).find(x=>x.id==='custom:'+external.id),anchor=routeAnchor(p,spec,'start'),perimeter=perimeterAnchor(p,box.id,ctrl.id,'p1');
assert.deepEqual(anchor,perimeter);
routeRecord(p,spec.id).points=[{x:6,y:6}];
assert.equal(deleteRoute(p,spec.id),true);
assert.equal(p.installation.connections.some(x=>x.id===external.id),false);
assert.equal(p.installation.routes[spec.id],undefined);
const template=saveBoxTemplate(lib,box);const copy=addBoxFromTemplate(p,template);assert.equal(copy.components.length,3);assert.equal(copy.components[0].sourceKey,'');
assert.ok(billOfMaterials(p).some(row=>row.name==='Control rack'));
assert.doesNotThrow(()=>validateProject(JSON.parse(JSON.stringify(p))));
const demo=createDemoProject(defaultLibrary());
assert.doesNotThrow(()=>validateProject(JSON.parse(JSON.stringify(demo))));
assert.ok(demo.installation.boxes.length>=2);
assert.ok(routeSpecs(demo).some(s=>routeIssues(demo,s).state==='short'));
assert.ok(routeSpecs(demo).some(s=>routeIssues(demo,s).issues.some(w=>w.includes('Expected'))));
assert.deepEqual(routeIssues(demo,routeSpecs(demo).find(s=>s.id==='custom:demo-input')).issues,[]);
console.log('Passed: physical route length, pivots, slack, cable shortfall warning, box capacity, typed mismatch, templates, BOM and project round-trip.');
